<?php
declare(strict_types=1);

/**
 * Serves uploaded files after checking that the logged-in user may see them.
 *   download.php?type=report&id=<report id>   report photo
 *   download.php?type=update&id=<file id>     technician proof (photo/video)
 *   download.php?type=avatar&id=<user id>     profile picture
 */

require __DIR__ . '/includes/bootstrap.php';

$user = require_login();
$type = (string) ($_GET['type'] ?? '');
$id = (int) ($_GET['id'] ?? 0);

$path = null;
$mime = null;
$name = 'file';

if ($type === 'avatar') {
    $row = q('SELECT avatar FROM users WHERE id = ?', [$id])->fetch();
    if ($row && $row['avatar']) {
        $path = APP_ROOT . '/uploads/avatars/' . $row['avatar'];
    }
} elseif ($type === 'report') {
    $report = find_report_for($user, $id);
    if ($report && $report['photo']) {
        $path = APP_ROOT . '/uploads/reports/' . $report['photo'];
    }
} elseif ($type === 'update') {
    $file = q(
        'SELECT uf.*, ru.report_id FROM update_files uf JOIN report_updates ru ON ru.id = uf.update_id WHERE uf.id = ?',
        [$id]
    )->fetch();
    if ($file && find_report_for($user, (int) $file['report_id'])) {
        $path = APP_ROOT . '/uploads/updates/' . $file['stored_name'];
        $mime = $file['mime'];
        $name = $file['original_name'];
    }
}

// Stored names are generated by us (hex + extension); refuse anything else.
if ($path === null || !preg_match('/^[a-f0-9]{32}\.[a-z0-9]{2,4}$/', basename($path)) || !is_file($path)) {
    http_response_code(404);
    exit('File not found.');
}

$mime ??= (new finfo(FILEINFO_MIME_TYPE))->file($path);
header('Content-Type: ' . $mime);
header('Content-Length: ' . filesize($path));
header('X-Content-Type-Options: nosniff');
header('Content-Disposition: inline; filename="' . preg_replace('/[^A-Za-z0-9._-]/', '_', $name) . '"');
header('Cache-Control: private, max-age=3600');
readfile($path);
